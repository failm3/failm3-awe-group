const assert = require('node:assert/strict');
const { decodeSeparated } = require('../core/decoder.cjs');

const bad = (t, msg) => assert.throws(() => decodeSeparated(t), (e) => e.message === msg, JSON.stringify(t));

assert.deepEqual(decodeSeparated(''), []);
assert.deepEqual(decodeSeparated('WINDOW=3|RATE=0|LIMIT=1\r\nWINDOW=4|RATE=1|LIMIT=2'), [{WINDOW:3,RATE:0,LIMIT:1},{WINDOW:4,RATE:1,LIMIT:2}]);
assert.equal(decodeSeparated('WINDOW=3|RATE=0|LIMIT=1\rWINDOW=4|RATE=1|LIMIT=2').length, 2);
bad('WINDOW=3|RATE=0|LIMIT=1|', 'INVALID_FORMAT');
assert.deepEqual(decodeSeparated('"WINDOW=3"|"RATE=0"|"LIMIT=1"'), [{WINDOW:3,RATE:0,LIMIT:1}]);
assert.deepEqual(decodeSeparated('"WINDOW=3"|"RATE=0"|"LIMIT=1"|"COL= x|y=z\r\nq"""'), [{WINDOW:3,RATE:0,LIMIT:1,COL:'x|y=z\r\nq"'}]);
bad('"WINDOW=3"="x|y"|RATE=0|LIMIT=1','INVALID_FORMAT');
bad('"WINDOW=3"x|RATE=0|LIMIT=1','INVALID_FORMAT');
bad('"WINDOW=3','INVALID_FORMAT');
bad('WINDOW="3','INVALID_FORMAT');
bad('WINDOW=3"|RATE=0|LIMIT=1','INVALID_FORMAT');
bad('window=3|RATE=0|LIMIT=1','INVALID_FORMAT');
bad('1WINDOW=3|RATE=0|LIMIT=1','INVALID_FORMAT');
bad('=3|RATE=0|LIMIT=1','INVALID_FORMAT');
bad('WINDOW=3|WINDOW=3|RATE=0|LIMIT=1','INVALID_FORMAT');
bad('"WINDOW=3"|"WINDOW=4"|RATE=0|LIMIT=1','INVALID_FORMAT');
bad('WINDOW=3|RATE=0|LIMIT=1|X=1|X=2','INVALID_FORMAT');
assert.deepEqual(decodeSeparated('WINDOW= 3 |RATE=0|LIMIT=1'), [{WINDOW:3,RATE:0,LIMIT:1}]);
assert.deepEqual(decodeSeparated('WINDOW=3|RATE=0|LIMIT=1|COLOR=  red  '), [{WINDOW:3,RATE:0,LIMIT:1,COLOR:'red'}]);
assert.deepEqual(decodeSeparated('WINDOW=3|RATE=0|LIMIT=1|COLOR=   '), [{WINDOW:3,RATE:0,LIMIT:1,COLOR:''}]);
bad('WINDOW=03|RATE=0|LIMIT=1','INVALID_VALUE');
bad('WINDOW=+3|RATE=0|LIMIT=1','INVALID_VALUE');
bad('WINDOW=-3|RATE=0|LIMIT=1','INVALID_VALUE');
bad('WINDOW=3.0|RATE=0|LIMIT=1','INVALID_VALUE');
bad('WINDOW=2|RATE=0|LIMIT=1','INVALID_VALUE');
bad('WINDOW=21|RATE=0|LIMIT=1','INVALID_VALUE');
bad('WINDOW=3|RATE=41|LIMIT=1','INVALID_VALUE');
bad('WINDOW=3|RATE=0|LIMIT=0','INVALID_VALUE');
bad('WINDOW=3|RATE=0|LIMIT=151','INVALID_VALUE');
assert.deepEqual(decodeSeparated('WINDOW=20|RATE=40|LIMIT=150'), [{WINDOW:20,RATE:40,LIMIT:150}]);
bad('WINDOW=10000000000000000000|RATE=0|LIMIT=1','INVALID_VALUE');
bad('RATE=0|LIMIT=1','INVALID_VALUE');
bad('WINDOW=3|LIMIT=1','INVALID_VALUE');
bad('WINDOW=3|RATE=0','INVALID_VALUE');
assert.deepEqual(decodeSeparated('WINDOW=3|RATE=0|LIMIT=1|FLAGS=fast'), [{WINDOW:3,RATE:0,LIMIT:1,FLAGS:['fast']}]);
assert.deepEqual(decodeSeparated('WINDOW=3|RATE=0|LIMIT=1|FLAGS=safe,fast'), [{WINDOW:3,RATE:0,LIMIT:1,FLAGS:['safe','fast']}]);
bad('WINDOW=3|RATE=0|LIMIT=1|FLAGS=fast,fast','INVALID_VALUE');
bad('WINDOW=3|RATE=0|LIMIT=1|FLAGS=','INVALID_VALUE');
bad('WINDOW=3|RATE=0|LIMIT=1|FLAGS=fast,,safe','INVALID_VALUE');
bad('WINDOW=3|RATE=0|LIMIT=1|FLAGS=slow','INVALID_VALUE');
bad('WINDOW=3|RATE=0|LIMIT=1|FLAGS=fast,safe,','INVALID_VALUE');
bad('WINDOW=99|RATE=0|LIMIT=1|X=1|X=2','INVALID_FORMAT');
bad('WINDOW=99|RATE=0|LIMIT=1|bad=1','INVALID_FORMAT');
const r = decodeSeparated('Z=9|COLOR=blue|Y=8|FLAGS=safe|LIMIT=5|RATE=2|WINDOW=7');
assert.deepEqual(Object.keys(r[0]), ['WINDOW','RATE','LIMIT','FLAGS','COLOR','Z','Y']);
assert.deepEqual(r[0], {WINDOW:7,RATE:2,LIMIT:5,FLAGS:['safe'],COLOR:'blue',Z:'9',Y:'8'});
const p = decodeSeparated('WINDOW=3|RATE=0|LIMIT=1|__PROTO__=x|CONSTRUCTOR=y');
assert.equal(Object.getPrototypeOf(p[0]), Object.prototype);
assert.equal(p[0].__PROTO__, 'x');
assert.equal(Object.prototype.hasOwnProperty.call(p[0],'CONSTRUCTOR'), true);
const q = decodeSeparated('WINDOW=3|RATE=0|LIMIT=1|COUNT=007');
assert.equal(q[0].COUNT, '007');
const t = decodeSeparated('WINDOW=3|RATE=0|LIMIT=1|TXT=  hi  ');
assert.equal(t[0].TXT, 'hi');
assert.equal(decodeSeparated('WINDOW=3|RATE=0|LIMIT=1\n\nWINDOW=4|RATE=0|LIMIT=2').length, 2);
console.log('extra PASS');
