const { parseRecords } = require('./lib/records.cjs');
const eq = (a,b)=>JSON.stringify(a)===JSON.stringify(b);
let pass=0, fail=0;
const ok=(n,g,e)=>{ if(eq(g,e)) pass++; else { fail++; console.log('FAIL',n,JSON.stringify(g),'!==',JSON.stringify(e)); } };
const th=(n,f,m)=>{ try{ f(); fail++; console.log('FAIL no-throw',n);}catch(e){ if(e.message===m) pass++; else {fail++; console.log('FAIL msg',n,e.message,'!==',m);} } };

ok('empty', parseRecords(''), []);
ok('basic', parseRecords('WINDOW=2;RATE=1;LIMIT=2'), [{WINDOW:2,RATE:1,LIMIT:2}]);
ok('bounds', parseRecords('WINDOW=20;RATE=0;LIMIT=1'), [{WINDOW:20,RATE:0,LIMIT:1}]);
ok('crlf multi', parseRecords('WINDOW=3;RATE=2;LIMIT=4\r\nWINDOW=1;RATE=0;LIMIT=25'), [{WINDOW:3,RATE:2,LIMIT:4},{WINDOW:1,RATE:0,LIMIT:25}]);
ok('cr only', parseRecords('WINDOW=3;RATE=2;LIMIT=4\rWINDOW=1;RATE=0;LIMIT=25').length, 2);
ok('trailing newline', parseRecords('WINDOW=2;RATE=1;LIMIT=2\n').length, 1);
ok('unknown dropped', parseRecords('WINDOW=2;RATE=1;LIMIT=2;FOO=bar'), [{WINDOW:2,RATE:1,LIMIT:2}]);
ok('unknown empty value', parseRecords('WINDOW=2;RATE=1;LIMIT=2;FOO='), [{WINDOW:2,RATE:1,LIMIT:2}]);
ok('quoted whole field', parseRecords('"WINDOW=2";RATE=1;LIMIT=2'), [{WINDOW:2,RATE:1,LIMIT:2}]);
ok('quoted sep/eq dropped', parseRecords('"COLOR=a;b=c";WINDOW=2;RATE=1;LIMIT=2'), [{WINDOW:2,RATE:1,LIMIT:2}]);
ok('quoted multiline', parseRecords('"COLOR=x\r\ny";WINDOW=2;RATE=1;LIMIT=2').length, 1);
ok('schema key order', Object.keys(parseRecords('"COLOR=c";"FLAGS=1";"WINDOW=2";RATE=1;LIMIT=2')[0]), ['WINDOW','RATE','LIMIT']);
ok('result values numbers', parseRecords('WINDOW=2;RATE=1;LIMIT=2')[0].WINDOW, 2);
th('unterminated', ()=>parseRecords('"WINDOW=2;RATE=1;LIMIT=2'), 'INVALID_FORMAT');
th('after quote', ()=>parseRecords('"WINDOW=2"x;RATE=1;LIMIT=2'), 'INVALID_FORMAT');
th('quote in unquoted', ()=>parseRecords('WINDOW=2"x";RATE=1;LIMIT=2'), 'INVALID_FORMAT');
th('dup decoded', ()=>parseRecords('"WINDOW=2";WINDOW=2;RATE=1;LIMIT=2'), 'INVALID_FORMAT');
th('bad key', ()=>parseRecords('window=2;RATE=1;LIMIT=2'), 'INVALID_FORMAT');
th('two equals', ()=>parseRecords('WINDOW=2=3;RATE=1;LIMIT=2'), 'INVALID_FORMAT');
th('ws value', ()=>parseRecords('COLOR= x;WINDOW=2;RATE=1;LIMIT=2'), 'INVALID_FORMAT');
th('empty field', ()=>parseRecords('WINDOW=2;;RATE=1;LIMIT=2'), 'INVALID_FORMAT');
th('missing required', ()=>parseRecords('WINDOW=2;RATE=1'), 'INVALID_VALUE');
th('rate 11', ()=>parseRecords('WINDOW=2;RATE=11;LIMIT=2'), 'INVALID_VALUE');
th('window 0', ()=>parseRecords('WINDOW=0;RATE=1;LIMIT=2'), 'INVALID_VALUE');
th('window 21', ()=>parseRecords('WINDOW=21;RATE=1;LIMIT=2'), 'INVALID_VALUE');
th('leading zero', ()=>parseRecords('WINDOW=02;RATE=1;LIMIT=2'), 'INVALID_VALUE');
th('limit 0', ()=>parseRecords('WINDOW=2;RATE=1;LIMIT=0'), 'INVALID_VALUE');
th('empty window', ()=>parseRecords('WINDOW=;RATE=1;LIMIT=2'), 'INVALID_VALUE');
th('syntax before semantic', ()=>parseRecords('WINDOW=99;RATE=1;LIMIT=2;BAD'), 'INVALID_FORMAT');
th('dup before semantic', ()=>parseRecords('WINDOW=99;WINDOW=99;RATE=1;LIMIT=2'), 'INVALID_FORMAT');
th('negative rate', ()=>parseRecords('WINDOW=2;RATE=-1;LIMIT=2'), 'INVALID_VALUE');
ok('proto key safe', Object.getPrototypeOf(parseRecords('"__proto__=x";WINDOW=2;RATE=1;LIMIT=2')[0]) === Object.prototype, true);
th('blank record in middle', ()=>parseRecords('WINDOW=2;RATE=1;LIMIT=2\n\nWINDOW=3;RATE=1;LIMIT=2'), 'INVALID_FORMAT');
console.log(`checks: ${pass} passed, ${fail} failed`);
